// Build the SPA against prod, bake index.html into convex/shell.ts (for per-game <head>), deploy functions, upload static files.
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
const PROD = process.env.PROD_URL ?? "https://small-mallard-255.convex.cloud";
const run = (cmd, env = {}) => execSync(cmd, { stdio: "inherit", env: { ...process.env, ...env } });
// Unique asset names per deploy (see vite.config.ts).
run("npx vite build", { VITE_CONVEX_URL: PROD, BUILD_ID: Date.now().toString(36) });
const html = readFileSync("dist/index.html", "utf8");
writeFileSync("convex/shell.ts", `// Generated by scripts/deploy.mjs from dist/index.html. Do not edit.\nexport const SHELL = ${JSON.stringify(html)};\n`);
run("npx tsc -p . && npx tsc -p convex");
// Static files first, then the functions that carry the new shell: the new shell never points at assets that
// aren't uploaded yet (a request in that gap used to get a 404 the CDN then cached for hours).
run("npx @convex-dev/static-hosting deploy --skip-build --skip-convex");
run("npx convex deploy -y");
console.log("Deployed:", PROD.replace(".convex.cloud", ".convex.site"));
